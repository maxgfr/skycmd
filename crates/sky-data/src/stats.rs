//! `stats`: summary tables of the produced data, written as Markdown.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::io::{BufRead, BufReader};
use std::path::{Path, PathBuf};

use anyhow::Result;

use crate::record::{argmax, entropy_bits, read_jsonl, DecisionRecord, MlmRecord};
use crate::tok::{sequence_stats, HEAD_MAX_LEN, MAX_LEN};

#[derive(Default, Debug, Clone)]
pub struct DecisionSummary {
    pub splits: BTreeMap<String, usize>,
    pub types: BTreeMap<String, usize>,
    pub n: usize,
    pub mean_opts: f64,
    /// Mean entropy of the target distributions (bits): how soft the labels are.
    pub mean_target_entropy: f64,
    /// Entropy of the argmax-position distribution, normalized by log2(#options) (1 = uniform).
    pub label_balance: f64,
    pub mean_ins_chars: f64,
    pub mean_state_chars: f64,
}

pub fn summarize_decisions(recs: &[DecisionRecord]) -> DecisionSummary {
    let mut s = DecisionSummary { n: recs.len(), ..Default::default() };
    if recs.is_empty() {
        return s;
    }
    let mut pos: BTreeMap<usize, BTreeMap<usize, f64>> = BTreeMap::new();
    for r in recs {
        *s.splits.entry(r.split.clone()).or_default() += 1;
        *s.types.entry(r.t.clone()).or_default() += 1;
        s.mean_opts += r.opts.len() as f64;
        let t: Vec<f64> = r.target.iter().map(|&x| x as f64).collect();
        s.mean_target_entropy += entropy_bits(&t);
        *pos.entry(r.opts.len()).or_default().entry(argmax(&r.target)).or_default() += 1.0;
        s.mean_ins_chars += r.ins.chars().count() as f64;
        s.mean_state_chars += r.state.chars().count() as f64;
    }
    let n = recs.len() as f64;
    s.mean_opts /= n;
    s.mean_target_entropy /= n;
    s.mean_ins_chars /= n;
    s.mean_state_chars /= n;
    // Weighted mean over option counts of the normalized label entropy.
    let mut bal = 0.0;
    for (k, counts) in &pos {
        let c: Vec<f64> = counts.values().copied().collect();
        let w: f64 = c.iter().sum();
        if *k > 1 {
            bal += w * entropy_bits(&c) / (*k as f64).log2();
        }
    }
    s.label_balance = bal / n;
    s
}

fn jsonl_files(dir: &Path) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = fs::read_dir(dir)
        .map(|rd| rd.filter_map(|e| e.ok().map(|e| e.path())).filter(|p| p.extension().is_some_and(|e| e == "jsonl")).collect())
        .unwrap_or_default();
    v.sort();
    v
}

fn stem(p: &Path) -> String {
    p.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default()
}

/// Builds the Markdown report for `data/` (decisions, text, tokenizers).
pub fn build_report(data: &Path, tok_dir: Option<&Path>) -> Result<String> {
    let mut md = String::from("# skycmd data statistics\n\nGenerated by `sky-data stats`.\n\n");
    let mut decision_dirs = vec![("decisions", data.join("decisions"))];
    if data.join("games").exists() {
        decision_dirs.push(("games", data.join("games")));
    }
    for (title, dir) in &decision_dirs {
        let files = jsonl_files(dir);
        if files.is_empty() {
            continue;
        }
        writeln!(md, "## Decision records ({title})\n")?;
        writeln!(md, "| source | records | train | val | test | choice/score/noul | mean opts | target entropy (bits) | label balance | ins chars | state chars |")?;
        writeln!(md, "|---|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|")?;
        let mut all = DecisionSummary::default();
        for f in &files {
            let recs: Vec<DecisionRecord> = read_jsonl(f)?;
            let s = summarize_decisions(&recs);
            all.n += s.n;
            for (k, v) in &s.splits {
                *all.splits.entry(k.clone()).or_default() += v;
            }
            let g = |k: &str| s.splits.get(k).copied().unwrap_or(0);
            let ty = |k: &str| s.types.get(k).copied().unwrap_or(0);
            writeln!(
                md,
                "| {} | {} | {} | {} | {} | {}/{}/{} | {:.2} | {:.3} | {:.3} | {:.0} | {:.0} |",
                stem(f),
                s.n,
                g("train"),
                g("val"),
                g("test"),
                ty("choice"),
                ty("score"),
                ty("noul"),
                s.mean_opts,
                s.mean_target_entropy,
                s.label_balance,
                s.mean_ins_chars,
                s.mean_state_chars
            )?;
        }
        let g = |k: &str| all.splits.get(k).copied().unwrap_or(0);
        writeln!(md, "| **total** | {} | {} | {} | {} | | | | | | |\n", all.n, g("train"), g("val"), g("test"))?;
    }
    let text_files = jsonl_files(&data.join("text"));
    if !text_files.is_empty() {
        writeln!(md, "## MLM text\n")?;
        writeln!(md, "| source | docs | MB | mean chars |")?;
        writeln!(md, "|---|---:|---:|---:|")?;
        let (mut docs_all, mut bytes_all) = (0usize, 0u64);
        for f in &text_files {
            let (mut docs, mut bytes, mut chars) = (0usize, 0u64, 0usize);
            for line in BufReader::new(fs::File::open(f)?).lines() {
                let line = line?;
                if let Ok(r) = serde_json::from_str::<MlmRecord>(&line) {
                    docs += 1;
                    bytes += r.text.len() as u64;
                    chars += r.text.chars().count();
                }
            }
            docs_all += docs;
            bytes_all += bytes;
            writeln!(md, "| {} | {} | {:.1} | {:.0} |", stem(f), docs, bytes as f64 / 1e6, chars as f64 / docs.max(1) as f64)?;
        }
        writeln!(md, "| **total** | {} | {:.1} | |\n", docs_all, bytes_all as f64 / 1e6)?;
    }
    if let Some(tok_dir) = tok_dir {
        let mut toks: Vec<PathBuf> = fs::read_dir(tok_dir)
            .map(|rd| rd.filter_map(|e| e.ok().map(|e| e.path())).filter(|p| p.extension().is_some_and(|e| e == "json")).collect())
            .unwrap_or_default();
        toks.sort();
        for t in toks {
            let Ok(tok) = tokenizers::Tokenizer::from_file(&t) else { continue };
            writeln!(md, "## Sequence lengths with `{}` (max_len {MAX_LEN}, head_max_len {HEAD_MAX_LEN})\n", stem(&t))?;
            writeln!(md, "| source | sampled | mean tokens | mean untruncated | truncated (any part) | options cut off |")?;
            writeln!(md, "|---|---:|---:|---:|---:|---:|")?;
            for (_, dir) in &decision_dirs {
                for (src, s) in sequence_stats(&tok, dir, 2000, 0)? {
                    writeln!(
                        md,
                        "| {src} | {} | {:.1} | {:.1} | {:.1}% | {:.1}% |",
                        s.n,
                        s.mean_tokens,
                        s.mean_untruncated,
                        100.0 * s.truncated_frac,
                        100.0 * s.markers_lost_frac
                    )?;
                }
            }
            md.push('\n');
        }
    }
    Ok(md)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::record::Question;

    #[test]
    fn summary_numbers() {
        let q = Question::noul("x");
        let mut a = q.record("s", "abcd", vec![0.0, 1.0]);
        let mut b = q.record("s", "ab", vec![0.5, 0.5]);
        b.split = "val".into();
        a.ins = "xy".into();
        let s = summarize_decisions(&[a, b]);
        assert_eq!(s.n, 2);
        assert_eq!(s.splits["train"], 1);
        assert!((s.mean_target_entropy - 0.5).abs() < 1e-9);
        assert!((s.label_balance - 1.0).abs() < 1e-9, "argmax 1 and 0 -> balanced");
        assert!((s.mean_state_chars - 3.0).abs() < 1e-9);
    }
}
